// 声明延时函数
void Delay_ms(uint32_t ms);

// ==================== 基础配置 ====================
#define ILI9341_WIDTH   240
#define ILI9341_HEIGHT  320

// 标准颜色定义
#define ILI9341_BLACK   0x0000
#define ILI9341_BLUE    0x001F
#define ILI9341_RED     0xF800
#define ILI9341_GREEN   0x07E0
#define ILI9341_CYAN    0x07FF
#define ILI9341_MAGENTA 0xF81F
#define ILI9341_YELLOW  0xFFE0
#define ILI9341_WHITE   0xFFFF

// 你的引脚定义（完全不变）
#define ILI9341_CS_GPIO_PORT    GPIOA
#define ILI9341_CS_GPIO_PIN     GPIO_Pin_5
#define ILI9341_DC_GPIO_PORT    GPIOA
#define ILI9341_DC_GPIO_PIN     GPIO_Pin_6
#define ILI9341_RST_GPIO_PORT   GPIOA
#define ILI9341_RST_GPIO_PIN    GPIO_Pin_7
#define ILI9341_BL_GPIO_PORT    GPIOB
#define ILI9341_BL_GPIO_PIN     GPIO_Pin_0

#define ILI9341_SPI             SPI2

// ILI9341 命令
#define ILI9341_SWRESET   0x01
#define ILI9341_SLPOUT    0x11
#define ILI9341_PIXFMT    0x3A
#define ILI9341_MADCTL    0x36
#define ILI9341_DISPON    0x29
#define ILI9341_CASET     0x2A
#define ILI9341_PASET     0x2B
#define ILI9341_RAMWR     0x2C

// ==================== 引脚操作 ====================
static void ILI9341_CS_LOW(void)  { GPIO_ResetBits(ILI9341_CS_GPIO_PORT, ILI9341_CS_GPIO_PIN); }
static void ILI9341_CS_HIGH(void) { GPIO_SetBits(ILI9341_CS_GPIO_PORT, ILI9341_CS_GPIO_PIN); }
static void ILI9341_DC_LOW(void)  { GPIO_ResetBits(ILI9341_DC_GPIO_PORT, ILI9341_DC_GPIO_PIN); }
static void ILI9341_DC_HIGH(void) { GPIO_SetBits(ILI9341_DC_GPIO_PORT, ILI9341_DC_GPIO_PIN); }
static void ILI9341_RST_LOW(void) { GPIO_ResetBits(ILI9341_RST_GPIO_PORT, ILI9341_RST_GPIO_PIN); }
static void ILI9341_RST_HIGH(void){ GPIO_SetBits(ILI9341_RST_GPIO_PORT, ILI9341_RST_GPIO_PIN); }
static void ILI9341_BL_ON(void)   { GPIO_SetBits(ILI9341_BL_GPIO_PORT, ILI9341_BL_GPIO_PIN); }

// ==================== 优化SPI函数（提高速度）====================
static void ILI9341_SPI_Send(uint8_t data) {
    SPI_I2S_SendData(ILI9341_SPI, data);
    while(SPI_I2S_GetFlagStatus(ILI9341_SPI, SPI_I2S_FLAG_TXE) == RESET);
}

// 发送命令/数据
static void ILI9341_SendCommand(uint8_t cmd) { ILI9341_DC_LOW(); ILI9341_CS_LOW(); ILI9341_SPI_Send(cmd); ILI9341_CS_HIGH(); }
static void ILI9341_SendData(uint8_t data)   { ILI9341_DC_HIGH(); ILI9341_CS_LOW(); ILI9341_SPI_Send(data); ILI9341_CS_HIGH(); }

// 设置显示窗口
static void ILI9341_SetWindow(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2) {
    ILI9341_SendCommand(ILI9341_CASET);
    ILI9341_SendData(x1>>8); ILI9341_SendData(x1&0xFF);
    ILI9341_SendData(x2>>8); ILI9341_SendData(x2&0xFF);

    ILI9341_SendCommand(ILI9341_PASET);
    ILI9341_SendData(y1>>8); ILI9341_SendData(y1&0xFF);
    ILI9341_SendData(y2>>8); ILI9341_SendData(y2&0xFF);

    ILI9341_SendCommand(ILI9341_RAMWR);
}

// ==================== 屏幕初始化（兼容所有ILI9341，不白屏）====================
void ILI9341_Init(void) {
    GPIO_InitTypeDef GPIO_InitStruct;
    SPI_InitTypeDef SPI_InitStruct;

    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOA | RCC_APB2Periph_GPIOB, ENABLE);
    RCC_APB1PeriphClockCmd(RCC_APB1Periph_SPI2, ENABLE);

    GPIO_InitStruct.GPIO_Pin = ILI9341_CS_GPIO_PIN | ILI9341_DC_GPIO_PIN | ILI9341_RST_GPIO_PIN;
    GPIO_InitStruct.GPIO_Mode = GPIO_Mode_Out_PP;
    GPIO_InitStruct.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init(GPIOA, &GPIO_InitStruct);

    GPIO_InitStruct.GPIO_Pin = ILI9341_BL_GPIO_PIN;
    GPIO_Init(GPIOB, &GPIO_InitStruct);

    GPIO_InitStruct.GPIO_Pin = GPIO_Pin_13 | GPIO_Pin_15;
    GPIO_InitStruct.GPIO_Mode = GPIO_Mode_AF_PP;
    GPIO_InitStruct.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init(GPIOB, &GPIO_InitStruct);

    SPI_InitStruct.SPI_Direction = SPI_Direction_1Line_Tx;
    SPI_InitStruct.SPI_Mode = SPI_Mode_Master;
    SPI_InitStruct.SPI_DataSize = SPI_DataSize_8b;
    SPI_InitStruct.SPI_CPOL = SPI_CPOL_Low;
    SPI_InitStruct.SPI_CPHA = SPI_CPHA_1Edge;
    SPI_InitStruct.SPI_NSS = SPI_NSS_Soft;
    SPI_InitStruct.SPI_BaudRatePrescaler = SPI_BaudRatePrescaler_4; 
    SPI_InitStruct.SPI_FirstBit = SPI_FirstBit_MSB;
    SPI_Init(ILI9341_SPI, &SPI_InitStruct);
    SPI_Cmd(ILI9341_SPI, ENABLE);

    ILI9341_RST_LOW();
    Delay_ms(200);
    ILI9341_RST_HIGH();
    Delay_ms(200);

    ILI9341_SendCommand(ILI9341_SWRESET); Delay_ms(150);
    ILI9341_SendCommand(ILI9341_SLPOUT);  Delay_ms(200);

    ILI9341_SendCommand(ILI9341_PIXFMT);
    ILI9341_SendData(0x55);

    ILI9341_SendCommand(ILI9341_MADCTL);
    ILI9341_SendData(0x48);  

    ILI9341_SendCommand(ILI9341_DISPON);
    Delay_ms(100);

    ILI9341_BL_ON();
    ILI9341_Clear(ILI9341_BLACK);
}

void ILI9341_Clear(uint16_t color) {
    ILI9341_SetWindow(0, 0, ILI9341_WIDTH-1, ILI9341_HEIGHT-1);
    ILI9341_DC_HIGH();
    ILI9341_CS_LOW();
    uint32_t i = 320*240;
    while(i--) {
        ILI9341_SPI_Send(color >> 8);
        ILI9341_SPI_Send(color & 0xFF);
    }
    ILI9341_CS_HIGH();
}

void ILI9341_DrawPixel(uint16_t x, uint16_t y, uint16_t color) {
    if(x >= 240 || y >= 320) return;
    ILI9341_SetWindow(x,y,x,y);
    ILI9341_DC_HIGH();
    ILI9341_CS_LOW();
    ILI9341_SPI_Send(color>>8);
    ILI9341_SPI_Send(color&0xFF);
    ILI9341_CS_HIGH();
}

// ==================== Basic drawing primitives ====================
void ILI9341_FillRect(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color) {
    uint32_t pixels;

    if (x1 >= ILI9341_WIDTH || y1 >= ILI9341_HEIGHT) return;
    if (x2 >= ILI9341_WIDTH) x2 = ILI9341_WIDTH - 1;
    if (y2 >= ILI9341_HEIGHT) y2 = ILI9341_HEIGHT - 1;
    if (x2 < x1 || y2 < y1) return;

    pixels = (uint32_t)(x2 - x1 + 1) * (uint32_t)(y2 - y1 + 1);
    ILI9341_SetWindow(x1, y1, x2, y2);
    ILI9341_DC_HIGH();
    ILI9341_CS_LOW();
    while (pixels--) {
        ILI9341_SPI_Send(color >> 8);
        ILI9341_SPI_Send(color & 0xFF);
    }
    ILI9341_CS_HIGH();
}

void ILI9341_DrawLine(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color) {
    int16_t dx, dy, sx, sy, err, e2;

    if (x1 == x2) {
        if (y2 < y1) {
            uint16_t t = y1;
            y1 = y2;
            y2 = t;
        }
        ILI9341_FillRect(x1, y1, x2, y2, color);
        return;
    }

    if (y1 == y2) {
        if (x2 < x1) {
            uint16_t t = x1;
            x1 = x2;
            x2 = t;
        }
        ILI9341_FillRect(x1, y1, x2, y2, color);
        return;
    }

    dx = (x1 > x2) ? (int16_t)(x1 - x2) : (int16_t)(x2 - x1);
    dy = (y1 > y2) ? (int16_t)(y1 - y2) : (int16_t)(y2 - y1);
    sx = (x1 < x2) ? 1 : -1;
    sy = (y1 < y2) ? 1 : -1;
    err = (dx > dy ? dx : -dy) / 2;

    while (1) {
        ILI9341_DrawPixel(x1, y1, color);
        if (x1 == x2 && y1 == y2) break;
        e2 = err;
        if (e2 > -dx) {
            err -= dy;
            x1 = (uint16_t)((int16_t)x1 + sx);
        }
        if (e2 < dy) {
            err += dx;
            y1 = (uint16_t)((int16_t)y1 + sy);
        }
    }
}

void ILI9341_DrawRect(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color) {
    ILI9341_DrawLine(x1, y1, x2, y1, color);
    ILI9341_DrawLine(x2, y1, x2, y2, color);
    ILI9341_DrawLine(x2, y2, x1, y2, color);
    ILI9341_DrawLine(x1, y2, x1, y1, color);
}

