static const uint16_t* ILI9341_FindGlyph16(uint16_t codepoint) {
    for (uint32_t i = 0; i < (sizeof(ILI9341_GLYPH16_TABLE) / sizeof(ILI9341_GLYPH16_TABLE[0])); i++) {
        if (ILI9341_GLYPH16_TABLE[i].codepoint == codepoint) return ILI9341_GLYPH16_TABLE[i].rows;
    }
    return 0;
}

static void ILI9341_PutGlyph16(uint16_t x, uint16_t y, const uint16_t rows[16], uint16_t color, uint16_t bg, uint8_t size) {
    for (uint8_t y_pos = 0; y_pos < 16; y_pos++) {
        uint16_t row = rows[y_pos];
        for (uint8_t x_pos = 0; x_pos < 16; x_pos++) {
            uint16_t px = (row & (0x8000 >> x_pos)) ? color : bg;
            for (uint8_t i = 0; i < size; i++) {
                for (uint8_t j = 0; j < size; j++) {
                    ILI9341_DrawPixel(x + x_pos * size + i, y + y_pos * size + j, px);
                }
            }
        }
    }
}

static uint8_t ILI9341_Utf8Decode(const uint8_t* p, uint16_t* out_codepoint) {
    if (p[0] < 0x80) {
        *out_codepoint = p[0];
        return 1;
    }
    if ((p[0] & 0xF0) == 0xE0 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80) {
        *out_codepoint = (uint16_t)(((p[0] & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F));
        return 3;
    }
    *out_codepoint = '?';
    return 1;
}

void ILI9341_PutString(uint16_t x, uint16_t y, const char* str, uint16_t color, uint16_t bg, uint8_t size) {
    const uint8_t* p = (const uint8_t*)str;
    while (*p) {
        uint16_t cp = 0;
        uint8_t n = ILI9341_Utf8Decode(p, &cp);
        if (cp < 0x80) {
            ILI9341_PutChar(x, y, (char)cp, color, bg, size);
            x += 8 * size;
        } else {
            const uint16_t* glyph = ILI9341_FindGlyph16(cp);
            if (glyph) {
                ILI9341_PutGlyph16(x, y, glyph, color, bg, size);
                x += 16 * size;
            } else {
                ILI9341_PutChar(x, y, ' ', color, bg, size);
                x += 8 * size;
            }
        }
        p += n;
    }
}

void ILI9341_DisplayData(double speed, float weight, GearLevel gear, MotorDirection direction) {
    char buffer[64];
    ILI9341_PutString(10, 10, "--- \xE7\x9B\x91\xE6\xB5\x8B ---", ILI9341_WHITE, ILI9341_BLACK, 1);
    
    snprintf(buffer, sizeof(buffer), "\xE8\xBD\xAC\xE9\x80\x9F:%4.0f  ", speed);
    ILI9341_PutString(10, 40, buffer, ILI9341_GREEN, ILI9341_BLACK, 2);
    ILI9341_PutRMin(160, 40, ILI9341_GREEN, ILI9341_BLACK, 2);
    
    snprintf(buffer, sizeof(buffer), "\xE8\xB5\xB7\xE9\x87\x8D\xE9\x87\x8F:%5.2f T", weight);
    ILI9341_PutString(10, 80, buffer, ILI9341_YELLOW, ILI9341_BLACK, 2);
    
    const char *gear_str;
    switch(gear){
        case GEAR_1: gear_str = "G1"; break;
        case GEAR_2: gear_str = "G2"; break;
        case GEAR_3: gear_str = "G3"; break;
        case GEAR_4: gear_str = "G4"; break;
        case GEAR_5: gear_str = "G5"; break;
        default: gear_str = "--"; break;
    }
    snprintf(buffer, sizeof(buffer), "\xE6\x8C\xA1\xE4\xBD\x8D:%s  ", gear_str);
    ILI9341_PutString(10, 120, buffer, ILI9341_CYAN, ILI9341_BLACK, 2);
    
    const char *dir_str;
    switch(direction){
        case DIRECTION_CW: dir_str = "\xE4\xB8\x8A\xE5\x8D\x87"; break;
        case DIRECTION_CCW: dir_str = "\xE4\xB8\x8B\xE9\x99\x8D"; break;
        case DIRECTION_STOP: dir_str = "\xE5\x81\x9C\xE6\xAD\xA2"; break;
        default: dir_str = "?? "; break;
    }
    snprintf(buffer, sizeof(buffer), "\xE8\xBD\xAC\xE5\x90\x91:%s  ", dir_str);
    ILI9341_PutString(10, 160, buffer, ILI9341_MAGENTA, ILI9341_BLACK, 2);
    
    snprintf(buffer, sizeof(buffer), "\xE6\xA8\xA1\xE5\xBC\x8F:\xE7\x9B\x91\xE6\xB5\x8B   ");
    ILI9341_PutString(10, 200, buffer, ILI9341_BLUE, ILI9341_BLACK, 2);
}
